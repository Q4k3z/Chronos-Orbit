const lower = new Map(Object.entries(messages).map(([key, value]) => [key.trim().toLocaleLowerCase('vi'), value.trim()]));
const originals = new WeakMap();
const listeners = new Set();
const isBrowser = typeof document !== 'undefined';
const storageKey = isBrowser && new URLSearchParams(location.search).get('test') === '1'
  ? 'chronos-test-language' : 'chronos-language';
export let language = 'vi';
if (isBrowser) {
  try { if (localStorage.getItem(storageKey) === 'en') language = 'en'; } catch (_) { /* Optional storage. */ }
}
export function t(source, lang = language) {
  if (lang !== 'en' || typeof source !== 'string') return source;
  const trimmed = source.trim();
  const prefix = trimmed.match(/^[^A-Za-zÀ-ỹ0-9]*/u)?.[0] || '';
  const core = trimmed.slice(prefix.length).replace(/\s*↗$/, '');
  const translated = lower.get(core.toLocaleLowerCase('vi'));
  if (translated) return source.replace(trimmed, prefix + translated + (trimmed.endsWith('↗') ? ' ↗' : ''));
  if (/^\d+,\d+×$/.test(trimmed)) return source.replace(',', '.');
  return source;
}
export function bodyName(data, lang = language) { return lang === 'en' ? t(data.nameVi, lang) : data.nameVi; }
export function onLanguageChange(callback) { listeners.add(callback); return () => listeners.delete(callback); }
export function translateContent(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (!node.parentElement?.closest('script, style')) node.nodeValue = t(node.nodeValue);
  }
}
export function translateUI(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.parentElement?.closest('script, style, #container, #panel-content, #scale-note')) continue;
    if (!originals.has(node)) originals.set(node, node.nodeValue);
    const value = t(originals.get(node));
    if (node.nodeValue !== value) node.nodeValue = value;
  }
  for (const element of root.querySelectorAll('[title], [aria-label]')) {
    let record = originals.get(element);
    if (!record) { record = {}; originals.set(element, record); }
    for (const attribute of ['title', 'aria-label']) {
      if (!element.hasAttribute(attribute)) continue;
      record[attribute] ??= element.getAttribute(attribute);
      element.setAttribute(attribute, t(record[attribute]));
    }
  }
}
export function setLanguage(value) {
  language = value === 'en' ? 'en' : 'vi';
  if (isBrowser) {
    document.documentElement.lang = language;
    try { localStorage.setItem(storageKey, language); } catch (_) { /* Optional storage. */ }
    translateUI();
    document.getElementById('language-select').value = language;
    listeners.forEach(callback => callback(language));
  }
}
if (isBrowser) {
  window.chronosT = t;
  document.documentElement.lang = language;
  translateUI();
  const select = document.getElementById('language-select');
  if (select) { select.value = language; select.addEventListener('change', () => setLanguage(select.value)); }
}
